/**
 * Deterministic PRNG seeded by date string (e.g. "2026-10-17")
 * Ensures 100% of players worldwide receive the exact same 6 Pokémon on any given day.
 */
export function getDailyChallengeTeam(dateStr?: string): TeamPreset {
  const activeDate = dateStr || new Date().toISOString().split('T')[0];
  
  // Hash the date string into a deterministic 32-bit seed
  let seed = 0;
  for (let i = 0; i < activeDate.length; i++) {
    seed = (seed * 31 + activeDate.charCodeAt(i)) >>> 0;
  }

  // Linear congruential generator (LCG)
  const lcg = () => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 4294967296;
  };

  // Shuffle candidate pool deterministically using structural cloning
  const pool: Pokemon[] = DAILY_ROSTER_POOL.map((p) => ({
    ...p,
    types: [...p.types],
    baseStats: { ...p.baseStats },
    moves: p.moves.map((m) => enrichMoveWithMechanics({ ...m })),
  }));
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(lcg() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  const selectedSix = pool.slice(0, 6);

  return {
    id: `daily_${activeDate}`,
    name: `Daily Six · ${activeDate}`,
    tagline: 'Wordle-Style Daily Battle · Seeded Globally for All Players',
    strategyTag: 'BALANCE',
    difficulty: 'Strategic',
    description: 'Today’s six Level 100 Pokémon, hand-selected by the daily seed to test your tactical mastery against Champion Cynthia.',
    recommendedLead: `${selectedSix[0].species} (Recommended counter for Spiritomb)`,
    colorTheme: 'from-amber-400 via-yellow-500 to-slate-900',
    team: selectedSix,
  };
}

